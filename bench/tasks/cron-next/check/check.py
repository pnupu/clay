import sys
from datetime import datetime as D
sys.path.insert(0, sys.argv[1])
from cron import next_run
cases = [
    ("*/15 * * * *", D(2026, 1, 1, 10, 7), D(2026, 1, 1, 10, 15)),
    ("*/15 * * * *", D(2026, 1, 1, 10, 15), D(2026, 1, 1, 10, 30)),
    ("*/15 * * * *", D(2026, 1, 1, 10, 14, 59, 999), D(2026, 1, 1, 10, 15)),
    ("0 0 * * *", D(2026, 12, 31, 23, 59), D(2027, 1, 1, 0, 0)),
    ("0 0 29 2 *", D(2026, 3, 1), D(2028, 2, 29)),
    ("0 0 31 * *", D(2026, 4, 1), D(2026, 5, 31)),
    ("0 12 * * MON-FRI", D(2026, 11, 14, 13, 0), D(2026, 11, 16, 12, 0)),
    ("0 12 * * 7", D(2026, 11, 14), D(2026, 11, 15, 12, 0)),
    ("0 12 * * 0", D(2026, 11, 14), D(2026, 11, 15, 12, 0)),
    ("0 12 * * sun", D(2026, 11, 14), D(2026, 11, 15, 12, 0)),
    ("0 0 13 * 5", D(2026, 11, 1), D(2026, 11, 6)),
    ("0 0 13 * 5", D(2026, 11, 7), D(2026, 11, 13)),
    ("0 0 1 * 1", D(2026, 11, 24), D(2026, 11, 30)),
    ("0 0 1,15 * *", D(2026, 11, 2), D(2026, 11, 15)),
    ("5/15 * * * *", D(2026, 1, 1, 10, 50), D(2026, 1, 1, 11, 5)),
    ("1-30/10 9 * * *", D(2026, 1, 1, 9, 21), D(2026, 1, 2, 9, 1)),
    ("0 0 * JAN,jul *", D(2026, 2, 1), D(2026, 7, 1)),
    ("0 0 * * 5-7", D(2026, 11, 16), D(2026, 11, 20)),
    ("30 2 * * 6,0", D(2026, 11, 15, 3, 0), D(2026, 11, 21, 2, 30)),
    ("0 9-17/4 * * *", D(2026, 1, 1, 13, 0), D(2026, 1, 1, 17, 0)),
    ("0 0 */10 * *", D(2026, 1, 21, 0, 0), D(2026, 1, 31, 0, 0)),
    ("0 0 * * */2", D(2026, 11, 14), D(2026, 11, 15)),
]
for expr, after, want in cases:
    got = next_run(expr, after)
    assert got == want, (expr, after, got, want)
for bad in ["* * * *", "60 * * * *", "* 24 * * *", "* * 0 * *", "* * * 13 *", "* * * * 8",
            "*/0 * * * *", "a * * * *", "5-1 * * * *", "* * * FOO *"]:
    try:
        next_run(bad, D(2026, 1, 1))
        raise AssertionError(("expected ValueError", bad))
    except ValueError:
        pass
