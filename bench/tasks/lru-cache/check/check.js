const assert = require('node:assert');
const { LRUCache } = require(require('node:path').join(process.argv[2], 'lru.js'));
let c = new LRUCache(2);
assert.strictEqual(c.set('a', 1), c);
c.set('b', 2);
assert.strictEqual(c.get('a'), 1);
c.set('c', 3);
assert.strictEqual(c.has('b'), false);
assert.deepStrictEqual(c.keys(), ['a', 'c']);
assert.strictEqual(c.has('a'), true);
c.set('d', 4);
assert.deepStrictEqual(c.keys(), ['c', 'd'], 'has() must not change recency');
c.set('c', 30);
c.set('e', 5);
assert.deepStrictEqual(c.keys(), ['c', 'e'], 'update must refresh recency');
assert.strictEqual(c.get('c'), 30);
assert.strictEqual(c.get('zzz'), undefined);
assert.strictEqual(c.size, 2);
assert.strictEqual(c.delete('c'), true);
assert.strictEqual(c.delete('c'), false);
assert.strictEqual(c.size, 1);
c.size = 99; assert.strictEqual(c.size, 1);
const k1 = {}, k2 = {};
c = new LRUCache(3);
c.set(k1, 'x').set(k2, 'y').set(0, 'zero').set(undefined, 'u');
assert.strictEqual(c.get(k1), undefined);
assert.strictEqual(c.get(k2), 'y');
assert.strictEqual(c.get({}), undefined);
assert.strictEqual(c.get(undefined), 'u');
c.set('v', undefined);
assert.strictEqual(c.has('v'), true);
assert.strictEqual(c.get(0), undefined);
assert.deepStrictEqual(c.keys(), [k2, undefined, 'v']);
const z = new LRUCache(0);
z.set('a', 1);
assert.strictEqual(z.size, 0);
assert.strictEqual(z.get('a'), undefined);
c = new LRUCache(1000);
for (let i = 0; i < 200000; i++) c.set(i, i);
assert.strictEqual(c.size, 1000);
assert.strictEqual(c.keys()[0], 199000);
console.log('pass');
